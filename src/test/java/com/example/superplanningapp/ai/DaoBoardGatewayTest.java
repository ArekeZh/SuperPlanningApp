package com.example.superplanningapp.ai;

import com.example.superplanningapp.ai.BoardGateway.BoardInfo;
import com.example.superplanningapp.ai.BoardGateway.CreatedBoard;
import com.example.superplanningapp.ai.BoardGateway.CreatedList;
import com.example.superplanningapp.ai.BoardPlan.CardPlan;
import com.example.superplanningapp.ai.BoardPlan.ListPlan;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

/**
 * SQL шлюза на H2 в режиме PostgreSQL — ваша настоящая база не трогается.
 * Схема повторяет нужные таблицы из README.
 */
class DaoBoardGatewayTest {

    private static final int ME = 1;
    private static final int OTHER = 2;

    private String url;
    private DaoBoardGateway gateway;

    @BeforeEach
    void setUp() throws SQLException {
        url = "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1";
        try (Connection c = DriverManager.getConnection(url); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE boards (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "title VARCHAR(255) NOT NULL, description TEXT, user_id INTEGER NOT NULL, "
                    + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
            s.execute("CREATE TABLE board_members (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "board_id INTEGER NOT NULL REFERENCES boards(id) ON DELETE CASCADE, user_id INTEGER NOT NULL)");
            s.execute("CREATE TABLE lists (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "title VARCHAR(255) NOT NULL, board_id INTEGER NOT NULL REFERENCES boards(id) ON DELETE CASCADE, "
                    + "color VARCHAR(50) DEFAULT 'blue', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
            s.execute("CREATE TABLE cards (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "title VARCHAR(255) NOT NULL, description TEXT, list_id INTEGER NOT NULL REFERENCES lists(id) ON DELETE CASCADE, "
                    + "card_order INTEGER DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        }
        gateway = new DaoBoardGateway(() -> DriverManager.getConnection(url));
    }

    private int count(String table) throws SQLException {
        try (Connection c = DriverManager.getConnection(url); Statement s = c.createStatement();
             ResultSet rs = s.executeQuery("SELECT COUNT(*) FROM " + table)) {
            rs.next();
            return rs.getInt(1);
        }
    }

    private List<String> cardTitles(int listId) throws SQLException {
        List<String> titles = new ArrayList<>();
        try (Connection c = DriverManager.getConnection(url); Statement s = c.createStatement();
             ResultSet rs = s.executeQuery("SELECT title FROM cards WHERE list_id = " + listId + " ORDER BY card_order, id")) {
            while (rs.next()) titles.add(rs.getString(1));
        }
        return titles;
    }

    private static BoardPlan plan(String title, ListPlan... lists) {
        return new BoardPlan(title, "", List.of(lists));
    }

    private static ListPlan list(String title, String... cards) {
        List<CardPlan> cs = new ArrayList<>();
        for (String c : cards) cs.add(new CardPlan(c, c.equals("С описанием") ? "детали" : ""));
        return new ListPlan(title, cs);
    }

    @Test
    @DisplayName("createBoard записывает доску, списки и задачи в правильном порядке")
    void createBoardWritesEverything() throws SQLException {
        CreatedBoard created = gateway.createBoard(ME, plan("Сессия",
                list("Сделать", "Матан", "Физика", "С описанием"), list("Готово")));

        assertEquals(1, count("boards"));
        assertEquals(2, count("lists"));
        assertEquals(3, count("cards"));
        assertEquals(2, created.lists().size());
        assertEquals(List.of("Матан", "Физика", "С описанием"), cardTitles(created.lists().get(0).id()));
        assertTrue(created.lists().get(0).createdNow());

        BoardInfo board = gateway.boardsOf(ME).get(0);
        assertEquals(created.id(), board.id());
        assertTrue(board.owner());
        assertNull(board.description(), "Пустое описание хранится как NULL");
        assertEquals(List.of("Сделать", "Готово"), board.lists().stream().map(BoardGateway.ListInfo::title).toList());
    }

    @Test
    @DisplayName("Сбой посреди создания откатывает всё — «половины доски» не остаётся")
    void createBoardIsAtomic() throws SQLException {
        BoardPlan broken = plan("Сломанная", list("Нормальный", "задача"), list("x".repeat(300)));

        assertThrows(SQLException.class, () -> gateway.createBoard(ME, broken));

        assertEquals(0, count("boards"));
        assertEquals(0, count("lists"));
        assertEquals(0, count("cards"));
    }

    @Test
    @DisplayName("boardsOf: свои доски и доски, где пользователь участник; чужие — нет")
    void boardsOfRespectsAccess() throws SQLException {
        gateway.createBoard(ME, plan("Моя", list("Сделать")));
        int shared = gateway.createBoard(OTHER, plan("Общая", list("Сделать"))).id();
        gateway.createBoard(OTHER, plan("Чужая", list("Сделать")));
        try (Connection c = DriverManager.getConnection(url); Statement s = c.createStatement()) {
            s.execute("INSERT INTO board_members (board_id, user_id) VALUES (" + shared + ", " + ME + ")");
        }

        List<BoardInfo> mine = gateway.boardsOf(ME);

        assertEquals(List.of("Моя", "Общая"), mine.stream().map(BoardInfo::title).toList());
        assertTrue(mine.get(0).owner());
        assertFalse(mine.get(1).owner());
    }

    @Test
    @DisplayName("addCards: существующий список (без учёта регистра), задачи добавляются в конец")
    void addCardsToExistingList() throws SQLException {
        CreatedBoard board = gateway.createBoard(ME, plan("Курсовая", list("Сделать", "Введение", "Глава 1")));

        CreatedList result = gateway.addCards(board.id(), "СДЕЛАТЬ",
                List.of(new CardPlan("Глава 2", ""), new CardPlan("Заключение", "")));

        assertFalse(result.createdNow());
        assertEquals("Сделать", result.title(), "Возвращается настоящее название списка");
        assertEquals(1, count("lists"));
        assertEquals(List.of("Введение", "Глава 1", "Глава 2", "Заключение"), cardTitles(result.id()));
    }

    @Test
    @DisplayName("addCards: несуществующий список создаётся")
    void addCardsCreatesList() throws SQLException {
        CreatedBoard board = gateway.createBoard(ME, plan("Курсовая", list("Сделать")));

        CreatedList result = gateway.addCards(board.id(), "Идеи", List.of(new CardPlan("Тёмная тема", "")));

        assertTrue(result.createdNow());
        assertEquals(2, count("lists"));
        assertEquals(List.of("Тёмная тема"), cardTitles(result.id()));
    }

    @Test
    @DisplayName("addCards: сбой откатывает и созданный список")
    void addCardsIsAtomic() throws SQLException {
        CreatedBoard board = gateway.createBoard(ME, plan("Курсовая", list("Сделать")));

        assertThrows(SQLException.class, () -> gateway.addCards(board.id(), "Новый",
                List.of(new CardPlan("ок", ""), new CardPlan("y".repeat(300), ""))));

        assertEquals(1, count("lists"));
        assertEquals(0, count("cards"));
    }
}
